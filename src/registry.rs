pub(crate) fn edit_world(dir: &Path, world_file: &str) -> Result<(PathBuf, toml_edit::DocumentMut), String> {
    let p = dir.join(world_file);
    let text = std::fs::read_to_string(&p).map_err(|e| format!("read {}: {e}", p.display()))?;
    let doc = text
        .parse::<toml_edit::DocumentMut>()
        .map_err(|e| format!("parse {}: {e}", p.display()))?;
    Ok((p, doc))
}

/// A github package resolved to a commit and fetched into the cache.
pub struct Fetched {
    pub slug: String,
    /// What the package calls itself — the name a `[deps]` entry uses.
    pub name: String,
    pub tag: Option<String>,
    pub branch: Option<String>,
    pub commit: String,
}

/// Resolve `<org>/<repo>` to a tag (or the default branch's HEAD) and fetch
/// it. Touches no project file.
pub fn fetch(slug: &str) -> Result<Fetched, String> {
    if slug.split('/').count() != 2 || slug.split('/').any(|p| p.is_empty()) {
        return Err(format!("add: expected <org>/<repo>, got {slug:?}"));
    }
    let resolved = resolve(slug)?;
    let (tag, branch, commit) = match &resolved {
        Resolved::Tag(t, c) => (Some(t.clone()), None, c.clone()),
        Resolved::Branch(b, c) => (None, Some(b.clone()), c.clone()),
    };
    let root = ensure_cached(slug, &commit)?;
    // The dependency names itself; the repo name is only a fallback.
    let pkg_file = root.join("package.toml");
    let name = std::fs::read_to_string(&pkg_file)
        .map_err(|e| {
            format!(
                "add {slug}: read {}: {e}\nA trantor dependency is a package: it needs a \
                 package.toml at its root declaring what it provides.",
                pkg_file.display()
            )
        })
        .and_then(|t| {
            toml::from_str::<crate::manifest::Package>(&t)
                .map_err(|e| format!("parse {}: {e}", pkg_file.display()))
        })?
        .package
        .name;
    Ok(Fetched { slug: slug.to_string(), name, tag, branch, commit })
}

/// Write the one `[deps]` line into `manifest` (a world.toml or package.toml
/// under `dir`) and pin it in `dir`'s lock. Validation, and undoing this when
/// it fails, is the caller's.
pub fn record(dir: &Path, manifest: &str, dep_name: &str, f: &Fetched) -> Result<bool, String> {
    let (p, mut doc) = edit_world(dir, manifest)?;
    let deps = doc["deps"].or_insert(toml_edit::table());
    if let Some(t) = deps.as_table_mut() {
        t.set_implicit(false);
    }
    // Already there with this source: leave the line — and its comments — be.
    let present = deps.get(dep_name).and_then(|d| d.get("github")).and_then(|g| g.as_str()) == Some(f.slug.as_str());
    if !present {
        let mut inline = toml_edit::InlineTable::new();
        inline.insert("github", f.slug.as_str().into());
        deps[dep_name] = toml_edit::value(inline);
        crate::journal::write_atomic(&p, doc.to_string().as_bytes())?;
    }

    let mut lock = Lock::load(dir)?;
    lock.packages.retain(|e| e.name != dep_name);
    lock.packages.push(Entry {
        name: dep_name.to_string(),
        github: f.slug.clone(),
        tag: f.tag.clone(),
        branch: f.branch.clone(),
        commit: f.commit.clone(),
    });
    Ok(lock.save(dir)? || !present)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn semver_key_accepts_both_spellings_and_skips_prereleases() {
        assert_eq!(semver_key("v1.2.3").unwrap(), (1, 2, 3));
        assert_eq!(semver_key("0.21.0").unwrap(), (0, 21, 0));
        assert!(semver_key("v1.2.3-rc1").is_none(), "a prerelease is never what `add` meant");
        assert!(semver_key("release-2024").is_none());
        assert!(semver_key("v1.2").is_none());
    }

    #[test]
    fn newest_wins_numerically_not_lexically() {
        let mut v: Vec<_> = ["v1.9.0", "v1.10.0", "v1.2.0"].iter().map(|t| (semver_key(t).unwrap(), *t)).collect();
        v.sort();
        assert_eq!(v.last().unwrap().1, "v1.10.0", "lexical order would pick v1.9.0");
    }

    #[test]
    fn an_annotated_tag_resolves_to_the_commit_not_the_tag_object() {
        // The peeled `^{}` line is the commit; recording the tag object still
        // clones fine, so this bug hides until someone reads the lock.
        let out = "aaa1\trefs/tags/v1.0.0\nbbb2\trefs/tags/v1.0.0^{}\nccc3\trefs/tags/v0.9.0\n";
        let tags = parse_tags(out);
        assert_eq!(tags.get("v1.0.0").unwrap(), "bbb2");
        assert_eq!(tags.get("v0.9.0").unwrap(), "ccc3");
        assert!(!tags.contains_key("v1.0.0^{}"));
    }

    #[test]
    fn the_lock_round_trips_and_a_rewrite_is_a_no_op() {
        let d = std::env::temp_dir().join(format!("trantor-lock-{}", std::process::id()));
        std::fs::create_dir_all(&d).unwrap();
        let l = Lock {
            packages: vec![Entry {
                name: "base".into(),
                github: "org/repo".into(),
                tag: Some("v1.0.0".into()),
                branch: None,
                commit: "abc123".into(),
            }],
        };
        assert!(l.save(&d).unwrap(), "first write changes the file");
        let back = Lock::load(&d).unwrap();
        assert_eq!(back.packages, l.packages);
        assert!(!back.save(&d).unwrap(), "a second save must be a no-op");
        std::fs::remove_dir_all(&d).ok();
    }

    /// D-U1-3: no code path may reach api.github.com. The property is easy to
    /// lose to one convenient call, so it is asserted rather than intended.
    #[test]
    fn nothing_here_talks_to_the_github_api() {
        let src = include_str!("registry.rs");
        // Strip comments: this module DESCRIBES the host it avoids, and the
        // check is about what the code reaches, not what the prose says.
        let body: String = src
            .split("mod tests")
            .next()
            .unwrap()
            .lines()
            .filter(|l| !l.trim_start().starts_with("//"))
            .collect::<Vec<_>>()
            .join("\n");
        assert!(!body.contains("api.github.com"), "the no-token property is gone");
        assert!(body.contains("https://github.com/"), "positive control: the plain host is used");
    }
}
